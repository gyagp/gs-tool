/**
 * Standard 3D Gaussian Splatting File I/O (.PLY and antimatter15/SuperSplat .SPLAT binary formats)
 * Supports importing external scenes up to 1M+ splats to benchmark the PlayCanvas-grade WebGPU renderer,
 * and exporting reconstructed captures for downstream pipelines (SuperSplat, Postshot, Unreal, Blender).
 */

import { packSplatsForGPU, SplatCloudData } from '../sfm/reconstruct';

const SH_C0 = 0.28209479177387814;

function sigmoid(x: number): number {
  if (x >= 0) {
    const z = Math.exp(-x);
    return 1 / (1 + z);
  }
  const z = Math.exp(x);
  return z / (1 + z);
}

function logit(p: number): number {
  const clamped = Math.max(1e-4, Math.min(1 - 1e-4, p));
  return Math.log(clamped / (1 - clamped));
}

/**
 * Exports SplatCloudData to compact 32-byte `.splat` binary format
 */
export function exportToSplatBinary(cloud: SplatCloudData): Blob {
  const count = cloud.count;
  const buf = new ArrayBuffer(count * 32);
  const f32 = new Float32Array(buf);
  const u8 = new Uint8Array(buf);

  for (let i = 0; i < count; i++) {
    const baseF = i * 8;
    const baseU = i * 32;

    f32[baseF] = cloud.positions[i * 3];
    f32[baseF + 1] = cloud.positions[i * 3 + 1];
    f32[baseF + 2] = cloud.positions[i * 3 + 2];

    f32[baseF + 3] = cloud.scales[i * 3];
    f32[baseF + 4] = cloud.scales[i * 3 + 1];
    f32[baseF + 5] = cloud.scales[i * 3 + 2];

    u8[baseU + 24] = Math.max(0, Math.min(255, Math.round(cloud.colors[i * 4] * 255)));
    u8[baseU + 25] = Math.max(0, Math.min(255, Math.round(cloud.colors[i * 4 + 1] * 255)));
    u8[baseU + 26] = Math.max(0, Math.min(255, Math.round(cloud.colors[i * 4 + 2] * 255)));
    u8[baseU + 27] = Math.max(0, Math.min(255, Math.round(cloud.colors[i * 4 + 3] * 255)));

    // .splat stores quaternion as (w, x, y, z) mapped to [0..255] via q * 128 + 128
    const qx = cloud.quats[i * 4];
    const qy = cloud.quats[i * 4 + 1];
    const qz = cloud.quats[i * 4 + 2];
    const qw = cloud.quats[i * 4 + 3];
    u8[baseU + 28] = Math.max(0, Math.min(255, Math.round(qw * 128 + 128)));
    u8[baseU + 29] = Math.max(0, Math.min(255, Math.round(qx * 128 + 128)));
    u8[baseU + 30] = Math.max(0, Math.min(255, Math.round(qy * 128 + 128)));
    u8[baseU + 31] = Math.max(0, Math.min(255, Math.round(qz * 128 + 128)));
  }

  return new Blob([buf], { type: 'application/octet-stream' });
}

/**
 * Exports SplatCloudData to standard Inria / PlayCanvas SuperSplat compatible binary little-endian `.ply`
 */
export function exportToPlyBinary(cloud: SplatCloudData): Blob {
  const count = cloud.count;
  const header = [
    'ply',
    'format binary_little_endian 1.0',
    'comment Generated by HELIOS WebGPU Gaussian Splatting Studio',
    `element vertex ${count}`,
    'property float x',
    'property float y',
    'property float z',
    'property float nx',
    'property float ny',
    'property float nz',
    'property float f_dc_0',
    'property float f_dc_1',
    'property float f_dc_2',
    'property float opacity',
    'property float scale_0',
    'property float scale_1',
    'property float scale_2',
    'property float rot_0',
    'property float rot_1',
    'property float rot_2',
    'property float rot_3',
    'end_header\n'
  ].join('\n');

  const headerBytes = new TextEncoder().encode(header);
  const floatsPerVertex = 17;
  const bodyBuffer = new ArrayBuffer(count * floatsPerVertex * 4);
  const view = new DataView(bodyBuffer);

  for (let i = 0; i < count; i++) {
    const off = i * floatsPerVertex * 4;
    view.setFloat32(off + 0, cloud.positions[i * 3], true);
    view.setFloat32(off + 4, cloud.positions[i * 3 + 1], true);
    view.setFloat32(off + 8, cloud.positions[i * 3 + 2], true);

    view.setFloat32(off + 12, 0, true);
    view.setFloat32(off + 16, 0, true);
    view.setFloat32(off + 20, 0, true);

    // Convert RGB [0..1] to 0th-order Spherical Harmonics DC coefficients
    view.setFloat32(off + 24, (cloud.colors[i * 4] - 0.5) / SH_C0, true);
    view.setFloat32(off + 28, (cloud.colors[i * 4 + 1] - 0.5) / SH_C0, true);
    view.setFloat32(off + 32, (cloud.colors[i * 4 + 2] - 0.5) / SH_C0, true);

    view.setFloat32(off + 36, logit(cloud.colors[i * 4 + 3]), true);

    // Standard 3DGS PLY stores log(scale) and (rot_0=w, rot_1=x, rot_2=y, rot_3=z)
    view.setFloat32(off + 40, Math.log(Math.max(1e-6, cloud.scales[i * 3])), true);
    view.setFloat32(off + 44, Math.log(Math.max(1e-6, cloud.scales[i * 3 + 1])), true);
    view.setFloat32(off + 48, Math.log(Math.max(1e-6, cloud.scales[i * 3 + 2])), true);

    view.setFloat32(off + 52, cloud.quats[i * 4 + 3], true); // w
    view.setFloat32(off + 56, cloud.quats[i * 4], true);     // x
    view.setFloat32(off + 60, cloud.quats[i * 4 + 1], true); // y
    view.setFloat32(off + 64, cloud.quats[i * 4 + 2], true); // z
  }

  return new Blob([headerBytes, bodyBuffer], { type: 'application/octet-stream' });
}

/**
 * Parses `.splat` or binary `.ply` 3D Gaussian Splatting files into packed GPU buffers + Morton order
 */
export async function importSplatFile(file: File): Promise<SplatCloudData> {
  const buf = await file.arrayBuffer();
  const name = file.name.toLowerCase();

  if (name.endsWith('.splat')) {
    const count = Math.floor(buf.byteLength / 32);
    if (count === 0) throw new Error('Empty .splat file');

    const f32 = new Float32Array(buf, 0, count * 8);
    const u8 = new Uint8Array(buf, 0, count * 32);

    const positions = new Float32Array(count * 3);
    const scales = new Float32Array(count * 3);
    const quats = new Float32Array(count * 4);
    const colors = new Float32Array(count * 4);

    for (let i = 0; i < count; i++) {
      const bf = i * 8;
      const bu = i * 32;

      positions[i * 3] = f32[bf];
      positions[i * 3 + 1] = -f32[bf + 1]; // Flip Y-down CV convention to Y-up viewer
      positions[i * 3 + 2] = -f32[bf + 2];

      scales[i * 3] = Math.max(1e-5, f32[bf + 3]);
      scales[i * 3 + 1] = Math.max(1e-5, f32[bf + 4]);
      scales[i * 3 + 2] = Math.max(1e-5, f32[bf + 5]);

      colors[i * 4] = u8[bu + 24] / 255;
      colors[i * 4 + 1] = u8[bu + 25] / 255;
      colors[i * 4 + 2] = u8[bu + 26] / 255;
      colors[i * 4 + 3] = u8[bu + 27] / 255;

      const qw = (u8[bu + 28] - 128) / 128;
      const qx = (u8[bu + 29] - 128) / 128;
      const qy = -(u8[bu + 30] - 128) / 128;
      const qz = -(u8[bu + 31] - 128) / 128;
      const qLen = Math.hypot(qx, qy, qz, qw) || 1;
      quats[i * 4] = qx / qLen;
      quats[i * 4 + 1] = qy / qLen;
      quats[i * 4 + 2] = qz / qLen;
      quats[i * 4 + 3] = qw / qLen;
    }

    return packSplatsForGPU(positions, scales, quats, colors, count, true);
  }

  // Parse standard 3DGS binary_little_endian PLY
  const headerSlice = new Uint8Array(buf, 0, Math.min(buf.byteLength, 16384));
  const headerText = new TextDecoder().decode(headerSlice);
  const endHeaderToken = 'end_header\n';
  let headerEnd = headerText.indexOf(endHeaderToken);
  let tokenLen = endHeaderToken.length;
  if (headerEnd < 0) {
    headerEnd = headerText.indexOf('end_header\r\n');
    tokenLen = 'end_header\r\n'.length;
  }
  if (headerEnd < 0) {
    throw new Error('Invalid PLY header: missing end_header');
  }

  const dataOffset = headerEnd + tokenLen;
  const lines = headerText.slice(0, headerEnd).split(/\r?\n/);

  let vertexCount = 0;
  const props: { name: string; type: string; offset: number; size: number }[] = [];
  let stride = 0;
  let inVertexElement = false;

  const typeSize: Record<string, number> = {
    float: 4, float32: 4,
    double: 8, float64: 8,
    uchar: 1, uint8: 1, char: 1, int8: 1,
    ushort: 2, uint16: 2, short: 2, int16: 2,
    uint: 4, uint32: 4, int: 4, int32: 4
  };

  for (const line of lines) {
    const parts = line.trim().split(/\s+/);
    if (parts[0] === 'element') {
      inVertexElement = parts[1] === 'vertex';
      if (inVertexElement) vertexCount = parseInt(parts[2], 10);
    } else if (parts[0] === 'property' && inVertexElement) {
      const pType = parts[1];
      const pName = parts[2];
      const sz = typeSize[pType] ?? 4;
      props.push({ name: pName, type: pType, offset: stride, size: sz });
      stride += sz;
    }
  }

  if (vertexCount <= 0 || stride <= 0) {
    throw new Error('PLY file contains 0 vertices');
  }

  const propMap = new Map(props.map((p) => [p.name, p]));
  const view = new DataView(buf, dataOffset);
  const readVal = (rowOff: number, name: string, fallback = 0): number => {
    const p = propMap.get(name);
    if (!p) return fallback;
    const o = rowOff + p.offset;
    switch (p.type) {
      case 'float':
      case 'float32':
        return view.getFloat32(o, true);
      case 'uchar':
      case 'uint8':
        return view.getUint8(o);
      default:
        return view.getFloat32(o, true);
    }
  };

  const hasSH = propMap.has('f_dc_0');
  const hasScale = propMap.has('scale_0');
  const positions = new Float32Array(vertexCount * 3);
  const scales = new Float32Array(vertexCount * 3);
  const quats = new Float32Array(vertexCount * 4);
  const colors = new Float32Array(vertexCount * 4);

  // Detect whether file was exported by HELIOS (Y-up) or Inria/COLMAP (Y-down)
  const isHeliosPly = headerText.includes('HELIOS');
  const yFlip = isHeliosPly ? 1 : -1;

  for (let i = 0; i < vertexCount; i++) {
    const row = i * stride;
    positions[i * 3] = readVal(row, 'x', 0);
    positions[i * 3 + 1] = readVal(row, 'y', 0) * yFlip;
    positions[i * 3 + 2] = readVal(row, 'z', 0) * yFlip;

    if (hasScale) {
      scales[i * 3] = Math.exp(Math.max(-12, Math.min(4, readVal(row, 'scale_0', -4))));
      scales[i * 3 + 1] = Math.exp(Math.max(-12, Math.min(4, readVal(row, 'scale_1', -4))));
      scales[i * 3 + 2] = Math.exp(Math.max(-12, Math.min(4, readVal(row, 'scale_2', -4))));
    } else {
      scales[i * 3] = 0.015;
      scales[i * 3 + 1] = 0.015;
      scales[i * 3 + 2] = 0.015;
    }

    if (hasSH) {
      colors[i * 4] = Math.max(0, Math.min(1, 0.5 + SH_C0 * readVal(row, 'f_dc_0', 0)));
      colors[i * 4 + 1] = Math.max(0, Math.min(1, 0.5 + SH_C0 * readVal(row, 'f_dc_1', 0)));
      colors[i * 4 + 2] = Math.max(0, Math.min(1, 0.5 + SH_C0 * readVal(row, 'f_dc_2', 0)));
      colors[i * 4 + 3] = sigmoid(readVal(row, 'opacity', 2));
    } else {
      colors[i * 4] = readVal(row, 'red', 200) / 255;
      colors[i * 4 + 1] = readVal(row, 'green', 200) / 255;
      colors[i * 4 + 2] = readVal(row, 'blue', 200) / 255;
      colors[i * 4 + 3] = 0.92;
    }

    const qw = readVal(row, 'rot_0', 1);
    const qx = readVal(row, 'rot_1', 0);
    const qy = readVal(row, 'rot_2', 0) * yFlip;
    const qz = readVal(row, 'rot_3', 0) * yFlip;
    const qLen = Math.hypot(qx, qy, qz, qw) || 1;
    quats[i * 4] = qx / qLen;
    quats[i * 4 + 1] = qy / qLen;
    quats[i * 4 + 2] = qz / qLen;
    quats[i * 4 + 3] = qw / qLen;
  }

  return packSplatsForGPU(positions, scales, quats, colors, vertexCount, true);
}
